"""Recording wrapper around the SDK client a session calls.

The session's Chat-Completions provider calls
``client.chat.completions.create(stream=True, ...)`` for every model turn and
drains the stream.  :class:`RecordingClient` sits between the two: every
chat-completion call also asks the server for token IDs and log-probabilities,
and the per-call token data is kept in ``RecordingClient.calls``:

- the prompt token IDs the server rendered for the call,
- the generated token IDs,
- each generated token's log-probability,
- the generated bytes, which give the text exactly as the model wrote it.

Streamed and non-streamed calls are both recorded; the reply the session sees
is not changed, and nothing the recorder does can fail the model call: a value
it cannot read marks the record, it is never raised into the session.

A call is only as good as its checks:

- Token IDs and log-probabilities are kept only as a pair.  A reply in which
  they do not arrive one to one leaves the call without log-probabilities.
- The server is asked to name each log-probability's token by its ID; where it
  does, the two channels are compared token by token.
- The counts are compared with the server's own usage numbers, so tokens
  missing from both channels are noticed.

A session's sub-agents call through the same client.  Their calls are recorded
with ``scope`` ``"sub_agent"`` and kept apart: they are not the run's own
turns.
"""

from __future__ import annotations

import copy
import math
import threading
import time
from dataclasses import dataclass, field
from typing import Any

from turnstone.core.log import get_logger
from turnstone.core.session import inside_task_agent
from turnstone.rollout.settings import merge_into

log = get_logger(__name__)

PARENT = "parent"
SUB_AGENT = "sub_agent"
_ID_PREFIX = "token_id:"


@dataclass
class CallRecord:
    """Token data of one chat-completion call (one model turn)."""

    index: int
    streamed: bool
    request: dict[str, Any]
    # Whose call: the session's own turn, or one a sub-agent made.
    scope: str = PARENT
    prompt_token_ids: list[int] | None = None
    token_ids: list[int] = field(default_factory=list)
    # One per generated token while ``aligned``; emptied when it is not.
    logprobs: list[float] = field(default_factory=list)
    # The generated bytes, token by token joined: the text as the model wrote it.
    raw: bytearray = field(default_factory=bytearray)
    finish_reason: str | None = None
    usage: dict[str, int] | None = None
    # True once the reply ended normally: read to its end, with a finish reason.
    complete: bool = False
    error: str | None = None
    # False once any part of the reply carried token IDs and log-probabilities
    # that did not correspond one to one.
    aligned: bool = True
    misaligned_chunks: int = 0
    # Whether the server named each log-probability's token by ID, so the two
    # channels could be compared token by token.
    ids_checked: bool = False
    # Something in the reply the recorder could not read.
    unreadable: str | None = None
    chunks: int = 0
    seconds: float = 0.0
    # Clock readings (``time.monotonic``): when the request went out, when the
    # server last gave something, when the call was over (``None`` while it is
    # not).  ``longest_silence`` is the longest wait for the server's next part.
    started_at: float = 0.0
    last_heard_at: float = 0.0
    ended_at: float | None = None
    longest_silence: float = 0.0

    @property
    def raw_text(self) -> str:
        return bytes(self.raw).decode("utf-8", errors="replace")

    def heard(self, now: float) -> None:
        """Note that the server gave something at *now*."""
        self.longest_silence = max(self.longest_silence, now - self.last_heard_at)
        self.last_heard_at = now

    def end(self, now: float) -> None:
        self.ended_at = now
        self.seconds = now - self.started_at

    def silence(self, now: float) -> float | None:
        """Seconds a call still under way has gone without the server giving
        anything; ``None`` for a call that is over."""
        return None if self.ended_at is not None else now - self.last_heard_at

    def problems(self, *, require_id_check: bool = True) -> list[str]:
        """Why this call's token data cannot be trained on; empty when it can.

        *require_id_check*: also fail a call whose log-probabilities the server
        did not name by token ID, where only the counts could be compared.
        """
        found: list[str] = []
        if self.error:
            found.append(f"request failed: {self.error}")
        if not self.complete:
            found.append("the reply did not end normally")
        if self.unreadable:
            found.append(f"a value in the reply could not be read ({self.unreadable})")
        if self.prompt_token_ids is None:
            found.append("no prompt token IDs returned")
        if not self.token_ids:
            found.append("no generated token IDs returned")
        if not self.aligned:
            found.append(
                f"token IDs and log-probabilities did not arrive one to one "
                f"({self.misaligned_chunks} parts of the reply); the log-probabilities "
                "were dropped"
            )
        elif len(self.token_ids) != len(self.logprobs):
            found.append(
                f"{len(self.token_ids)} token IDs but {len(self.logprobs)} log-probabilities"
            )
        if self.usage is None:
            found.append("the server reported no usage to check the token counts against")
        else:
            completion = self.usage.get("completion_tokens")
            if completion != len(self.token_ids):
                found.append(
                    f"the server counted {completion} generated tokens, "
                    f"{len(self.token_ids)} were recorded"
                )
            prompt = self.usage.get("prompt_tokens")
            if self.prompt_token_ids is not None and prompt != len(self.prompt_token_ids):
                found.append(
                    f"the server counted {prompt} prompt tokens, "
                    f"{len(self.prompt_token_ids)} were recorded"
                )
        bad = bad_logprob_positions(self.logprobs)
        if bad:
            found.append(f"{len(bad)} impossible log-probabilities, first at {bad[0]}")
        if require_id_check and self.aligned and self.token_ids and not self.ids_checked:
            found.append(
                "the server did not name each log-probability's token by ID, so only the "
                "counts could be compared, not which token each value belongs to"
            )
        return found

    def to_dict(self, *, require_id_check: bool = True) -> dict[str, Any]:
        return {
            "index": self.index,
            "scope": self.scope,
            "streamed": self.streamed,
            "request": self.request,
            "prompt_token_ids": self.prompt_token_ids,
            "token_ids": self.token_ids,
            "logprobs": self.logprobs if self.aligned else None,
            "finish_reason": self.finish_reason,
            "usage": self.usage,
            "complete": self.complete,
            "error": self.error,
            "aligned": self.aligned,
            "misaligned_chunks": self.misaligned_chunks,
            "ids_checked": self.ids_checked,
            "chunks": self.chunks,
            "seconds": round(self.seconds, 3),
            "longest_silence": round(self.longest_silence, 3),
            "problems": self.problems(require_id_check=require_id_check),
        }

    def summary(self) -> dict[str, Any]:
        """The call without its token data: enough to see what happened."""
        usage = self.usage or {}
        return {
            "index": self.index,
            "scope": self.scope,
            "complete": self.complete,
            "finish_reason": self.finish_reason,
            "error": self.error,
            "prompt_tokens": usage.get("prompt_tokens"),
            "generated_tokens": usage.get("completion_tokens", len(self.token_ids)),
            "seconds": round(self.seconds, 3),
        }


def bad_logprob_positions(logprobs: list[float]) -> list[int]:
    """Positions whose value cannot be the log-probability of a sampled token.

    A sampled token has a finite log-probability at or below zero; a server
    writes a large negative marker for a token outside the sampled distribution.
    """
    return [i for i, v in enumerate(logprobs) if not (math.isfinite(v) and -100.0 < v <= 1e-6)]


def extra_field(obj: Any, name: str) -> Any:
    """A non-standard field of an SDK response object (the SDK keeps it as an extra)."""
    value = getattr(obj, name, None)
    if value is None:
        extras = getattr(obj, "model_extra", None)
        if isinstance(extras, dict):
            value = extras.get(name)
    return value


def logprob_entries(choice: Any) -> list[Any]:
    """The per-token log-probability entries of one choice, ``[]`` when it has none."""
    lp = getattr(choice, "logprobs", None)
    if lp is None:
        return []
    content = lp.get("content") if isinstance(lp, dict) else getattr(lp, "content", None)
    return list(content or [])


def entry_value(entry: Any, name: str) -> Any:
    return entry.get(name) if isinstance(entry, dict) else getattr(entry, name, None)


def _usage_dict(usage: Any) -> dict[str, int] | None:
    if usage is None:
        return None
    out: dict[str, int] = {}
    for name in ("prompt_tokens", "completion_tokens", "total_tokens"):
        value = usage.get(name) if isinstance(usage, dict) else getattr(usage, name, None)
        if value is not None:
            out[name] = int(value)
    return out


def _misaligned(record: CallRecord) -> None:
    # From here on a value could only be attached to the wrong token.
    record.misaligned_chunks += 1
    record.aligned = False
    record.logprobs.clear()


def _take_choice(record: CallRecord, choice: Any) -> None:
    """Add one choice's tokens to *record*, keeping IDs and values paired."""
    ids = [int(i) for i in (extra_field(choice, "token_ids") or [])]
    entries = logprob_entries(choice)
    record.token_ids.extend(ids)
    for entry in entries:
        data = entry_value(entry, "bytes")
        if data:
            record.raw.extend(bytes(data))
    if len(ids) != len(entries):
        _misaligned(record)
    elif record.aligned:
        values = [float(entry_value(e, "logprob")) for e in entries]
        named = [str(entry_value(e, "token")) for e in entries]
        if named and all(n.startswith(_ID_PREFIX) for n in named):
            record.ids_checked = True
            if named != [f"{_ID_PREFIX}{i}" for i in ids]:
                # Equal counts, different tokens: the channels are out of step.
                _misaligned(record)
                return
        record.logprobs.extend(values)
    reason = getattr(choice, "finish_reason", None)
    if reason:
        record.finish_reason = reason


def _take(record: CallRecord, part: Any) -> None:
    """Copy token data out of one chunk or whole response.  Never raises."""
    try:
        prompt_ids = extra_field(part, "prompt_token_ids")
        if prompt_ids is not None and record.prompt_token_ids is None:
            record.prompt_token_ids = [int(i) for i in prompt_ids]
        for choice in getattr(part, "choices", None) or []:
            if getattr(choice, "index", 0) == 0:
                _take_choice(record, choice)
        usage = _usage_dict(getattr(part, "usage", None))
        if usage:
            record.usage = usage
    except Exception as error:
        # A value of the wrong kind (a null log-probability, a token ID that is
        # no number).  The reply goes on to the session untouched; the record
        # says it cannot be trusted.
        record.unreadable = f"{type(error).__name__}: {str(error)[:200]}"
        if record.aligned:
            _misaligned(record)
        log.warning("rollout.recording_unreadable", call=record.index, error=record.unreadable)


class _RecordingStream:
    """Iterates an SDK stream, copying token data out of every chunk on the way."""

    def __init__(self, stream: Any, record: CallRecord, started: float) -> None:
        self._stream = stream
        self._record = record
        self._started = started

    def __iter__(self) -> Any:
        record = self._record
        try:
            for chunk in self._stream:
                record.heard(time.monotonic())
                record.chunks += 1
                _take(record, chunk)
                yield chunk
            record.complete = record.finish_reason is not None
        except BaseException as error:
            record.error = f"{type(error).__name__}: {str(error)[:300]}"
            raise
        finally:
            record.end(time.monotonic())

    def __enter__(self) -> _RecordingStream:
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()

    def close(self) -> None:
        close = getattr(self._stream, "close", None)
        if callable(close):
            close()

    def __getattr__(self, name: str) -> Any:
        # ``response`` (read by the provider's guard against a non-stream reply)
        # and whatever else the SDK stream offers.
        return getattr(self._stream, name)


class _Completions:
    def __init__(self, owner: RecordingClient, inner: Any) -> None:
        self._owner = owner
        self._inner = inner

    def create(self, **kwargs: Any) -> Any:
        owner = self._owner
        kwargs = dict(kwargs)
        kwargs["logprobs"] = True
        extra_body = copy.deepcopy(kwargs.get("extra_body") or {})
        merge_into(extra_body, owner.extra_body)
        extra_body["return_token_ids"] = True
        # Name each log-probability's token by its ID, to compare the channels.
        extra_body["return_tokens_as_token_ids"] = True
        kwargs["extra_body"] = extra_body
        streamed = bool(kwargs.get("stream"))
        messages = kwargs.get("messages") or []
        request: dict[str, Any] = {
            "model": kwargs.get("model"),
            "messages": len(messages),
            "roles": [m.get("role") for m in messages if isinstance(m, dict)],
            "tools": [t.get("function", {}).get("name") for t in kwargs.get("tools") or []],
            "sampling": {
                k: kwargs[k]
                for k in (
                    "temperature",
                    "top_p",
                    "max_tokens",
                    "max_completion_tokens",
                    "reasoning_effort",
                )
                if k in kwargs
            },
            "extra_body": dict(extra_body),
        }
        with owner._lock:
            record = CallRecord(
                index=len(owner.calls),
                streamed=streamed,
                request=request,
                scope=SUB_AGENT if inside_task_agent() else PARENT,
            )
            owner.calls.append(record)
        started = time.monotonic()
        record.started_at = record.last_heard_at = started
        try:
            response = self._inner.create(**kwargs)
        except BaseException as error:
            record.error = f"{type(error).__name__}: {str(error)[:300]}"
            record.end(time.monotonic())
            raise
        if streamed:
            # The headers are in: the server answered.
            record.heard(time.monotonic())
            return _RecordingStream(response, record, started)
        record.heard(time.monotonic())
        record.chunks = 1
        _take(record, response)
        record.complete = record.finish_reason is not None
        record.end(time.monotonic())
        return response

    def __getattr__(self, name: str) -> Any:
        return getattr(self._inner, name)


class _Chat:
    def __init__(self, owner: RecordingClient, inner: Any) -> None:
        self._inner = inner
        self.completions = _Completions(owner, inner.completions)

    def __getattr__(self, name: str) -> Any:
        return getattr(self._inner, name)


class RecordingClient:
    """An SDK client stand-in that records the token data of every chat-completion call.

    ``extra_body`` is merged into each request's extra body: sampler settings
    the SDK has no keyword for, chat-template arguments.  Everything else goes
    to the wrapped client untouched.
    """

    def __init__(
        self,
        inner: Any,
        *,
        extra_body: dict[str, Any] | None = None,
        _shared: RecordingClient | None = None,
    ) -> None:
        self._inner = inner
        self.calls: list[CallRecord]
        self._lock: threading.Lock
        if _shared is not None:
            # A per-call copy made by ``with_options``: same records, same settings.
            self.calls = _shared.calls
            self._lock = _shared._lock
            self.extra_body: dict[str, Any] = _shared.extra_body
        else:
            self.calls = []
            self._lock = threading.Lock()
            self.extra_body = dict(extra_body or {})
        self.chat = _Chat(self, inner.chat)

    def scoped(self, scope: str) -> list[CallRecord]:
        with self._lock:
            return [c for c in self.calls if c.scope == scope]

    def last_parent_call(self) -> CallRecord | None:
        calls = self.scoped(PARENT)
        return calls[-1] if calls else None

    def with_options(self, **kwargs: Any) -> RecordingClient:
        return RecordingClient(self._inner.with_options(**kwargs), _shared=self)

    def close(self) -> None:
        self._inner.close()

    def __getattr__(self, name: str) -> Any:
        return getattr(self._inner, name)
