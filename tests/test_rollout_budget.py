"""The model's own budgets, and the time limit as a backstop for the machinery.

Whole rollouts against the scripted chat server, like ``test_rollout_episode``:
the directory sandbox acts on this machine, takes the caller's say and is given
harmless commands only (``echo``, ``sleep``, ``yes | head``).
"""

