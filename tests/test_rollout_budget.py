# A server far faster than any minimum a test names, so that only a server the
# test slows down is too slow.
FAST = {"min_tokens_per_second": 1e6}


@pytest.fixture(autouse=True)
def _no_configuration_file(monkeypatch):
    monkeypatch.setattr(config_module, "_cache", {})


def _bash(command: str) -> dict[str, Any]:
    return {"tool_calls": [{"name": "bash", "arguments": {"command": command}}]}


def _generated(script: list[dict[str, Any]], **server: Any) -> list[int]:
    """The tokens each reply of *script* takes, from a run without a budget."""
    with ScriptedChatServer(script, **server) as scripted:
        record, _box = _run(scripted)
    return [len(call["token_ids"]) for call in record["tokens"]["calls"]]


class TestTheTokenBudget:
    """Tokens generated by the session and its sub-agents, together."""

    def test_a_reply_is_cut_at_what_is_left_and_the_rollout_ends_there(self):
        first, second, _third = _generated(SCRIPT)
        budget = first + 10
        with ScriptedChatServer(SCRIPT, keep_reply_limit=True) as server:
            task = Task(prompt="make a file", setup_files={"seed.txt": "s"})
            task.max_generated_tokens = budget
            record, _box = _run(server, task=task, **FAST)
            limits = [r.get("max_completion_tokens", r.get("max_tokens")) for r in server.requests]
        assert second > 10
        # The first request could have all of it, the second what was left.
        assert limits == [budget, 10]
        assert record["finish_state"] == "token_budget" and record["finish_cause"] == "model"
        assert record["trainable"] is True and record["one_sequence"] is True
        assert record["turns"] == 2 and record["generated_tokens"] == budget
        assert record["budgets"]["generated_tokens"] == budget
        assert record["budgets"]["wall_clock"] == "backstop for the machinery"
        # The cut reply's tool call did not run.
        assert len(record["tool_log"]) == 1

    def test_with_nothing_left_no_request_is_made(self):
        first, _second, _third = _generated(SCRIPT)
        with ScriptedChatServer(SCRIPT, keep_reply_limit=True) as server:
            task = Task(prompt="make a file", setup_files={"seed.txt": "s"})
            task.max_generated_tokens = first
            record, _box = _run(server, task=task, **FAST)
            requests = len(server.requests)
        assert requests == 1 and record["turns"] == 1
        assert record["finish_state"] == "token_budget" and record["trainable"] is True
        assert "budget of generated tokens is used up" in record["error"]
        assert len(record["tool_log"]) == 1 and record["tool_log"][0]["ok"] is True

    def test_a_rollout_that_stays_within_it_ends_as_it_would_have(self):
        with ScriptedChatServer(SCRIPT, keep_reply_limit=True) as server:
            task = Task(prompt="make a file", setup_files={"seed.txt": "s"})
            task.max_generated_tokens = 100_000
            record, _box = _run(server, task=task, **FAST)
        assert record["finish_state"] == "completed" and record["trainable"] is True
        assert record["budgets"]["generated_tokens"] == record["generated_tokens"]

    SPAWN = {"tool_calls": [{"name": "task_agent", "arguments": {"prompt": "Write the note."}}]}
    PARENT = [SPAWN, {"content": "The note is written."}]
    AGENT = [{"content": "A long report of what was done. " * 20}]

    def test_a_sub_agents_tokens_count_and_its_cut_reply_is_an_ordinary_result(self):
        """A budget of the episode, not of each sub-agent: what a sub-agent
        generates comes out of the same budget, and a sub-agent that runs into
        it hands back what it has."""
        with ScriptedChatServer(self.PARENT, agent_script=self.AGENT) as scripted:
            unbounded, _box = _run(scripted)
        first = len(unbounded["tokens"]["calls"][0]["token_ids"])
        whole = unbounded["subagents"]["generated_tokens"]
        budget = first + 40
        assert whole > 40
        with ScriptedChatServer(
            self.PARENT, agent_script=self.AGENT, keep_reply_limit=True
        ) as server:
            task = Task(prompt="delegate")
            task.max_generated_tokens = budget
            record, _box = _run(server, task=task, **FAST)
            parent_requests = len(server.parent_requests)
        # The sub-agent got what was left and returned; the session then had nothing.
        assert record["subagents"]["generated_tokens"] == 40
        assert record["subagents"]["failures"] == []
        assert record["tool_log"][0]["tool"] == "task_agent"
        assert parent_requests == 1
        assert record["finish_state"] == "token_budget" and record["finish_cause"] == "model"
        assert record["trainable"] is True
        assert record["budgets"]["generated_tokens"] == budget
        # The rollout's own length is still what the session generated.
        assert record["generated_tokens"] == first

    def test_a_sub_agent_with_nothing_left_fails_as_its_own_doing(self):
        with ScriptedChatServer(self.PARENT, agent_script=self.AGENT) as scripted:
            unbounded, _box = _run(scripted)
        first = len(unbounded["tokens"]["calls"][0]["token_ids"])
        with ScriptedChatServer(
            self.PARENT, agent_script=self.AGENT, keep_reply_limit=True
        ) as server:
            task = Task(prompt="delegate")
            task.max_generated_tokens = first
            record, _box = _run(server, task=task, **FAST)
            agent_requests = len(server.agent_requests)
        assert agent_requests == 0  # refused before it went out
        assert record["subagents"]["failures"] == [] and record["subagents"]["started"] == 1
        assert record["tool_log"][0]["ok"] is False
        assert record["finish_state"] == "token_budget" and record["trainable"] is True

    def test_endless_sub_agents_run_into_it(self):
        """Sub-agent after sub-agent: the budget ends it, as the model's outcome."""
        parent = [self.SPAWN] * 12 + [{"content": "done"}]
        agent = [{"content": "Some words from a sub-agent, every time. " * 3}]
        with ScriptedChatServer(parent, agent_script=agent, keep_reply_limit=True) as server:
            task = Task(prompt="delegate for ever", max_turns=15)
            task.max_generated_tokens = 600
            record, _box = _run(server, task=task, **FAST)
        assert record["finish_state"] == "token_budget" and record["finish_cause"] == "model"
        assert record["trainable"] is True and record["subagents"]["failures"] == []
        assert record["budgets"]["generated_tokens"] <= 600
        assert 1 <= record["subagents"]["started"] < 12


class TestTheCommandTime:
    """The time the model's commands run, while no model call is under way."""

    SLEEP = [_bash("sleep 30"), {"content": "never reached"}]

    @pytest.mark.parametrize("token_budget", [None, 100_000])
    def test_commands_that_run_too_long_end_the_rollout_as_the_models_outcome(self, token_budget):
        with ScriptedChatServer(self.SLEEP) as server:
            task = Task(prompt="wait", timeout=60)
            task.max_command_seconds = 1.5
            task.max_generated_tokens = token_budget
            record, box = _run(server, task=task, **(FAST if token_budget else {}))
            requests = len(server.requests)
        assert record["finish_state"] == "command_time" and record["finish_cause"] == "model"
        assert record["trainable"] is True and record["problems"] == []
        assert requests == 1 and record["turns"] == 1
        assert 1.5 <= record["budgets"]["command_seconds"] < 6
        assert record["seconds"] < 15 and box.closed == 1
        # Where the time went: the command, not the server.
        assert record["time"]["command_seconds"] > record["time"]["model_seconds"]

    def test_time_inside_a_sub_agents_model_calls_is_not_the_commands(self):
        """A sub-agent runs inside a tool call of the session.  What its model
        calls take is the server's time; only its commands' time is the commands'."""
        parent = [TestTheTokenBudget.SPAWN, {"content": "done"}]
        agent = [{"content": "a slow report"}]
        with ScriptedChatServer(parent, agent_script=agent, delay=1.0) as server:
            task = Task(prompt="delegate", timeout=60)
            task.max_command_seconds = 0.8
            record, _box = _run(server, task=task)
        assert record["finish_state"] == "completed", record["error"]
        assert record["time"]["model_seconds"] >= 3.0
        assert record["time"]["command_seconds"] < 0.8


class TestTheBackstop:
    """With a token budget the time limit is the machinery's: a run that reaches
    it is judged by how fast the server was for what it was asked to do."""

    def _task(self, **settings: Any) -> Task:
        task = Task(prompt="work", timeout=2, setup_files={"seed.txt": "s"})
        task.max_generated_tokens = 100_000
        for name, value in settings.items():
            setattr(task, name, value)
        return task

    def test_a_server_slow_over_the_prompt_is_the_machinerys_failure(self):
        with ScriptedChatServer(SCRIPT, delay=4.0) as server:
            record, _box = _run(server, task=self._task(), **FAST)
        assert record["finish_state"] == "backstop" and record["finish_cause"] == "machinery"
        assert record["trainable"] is False and record["one_sequence"] is False
        (problem,) = record["problems"]
        assert problem.startswith("the time limit passed with the model's budgets not used up")
        said = record["timeout"]
        assert said["cause"] == "the model server was slower than its configured minimum speed"
        assert said["model_seconds"] > said["model_seconds_at_minimum_speed"]
        # The time split is in the record.
        assert record["time"]["model_seconds"] >= 1.5 and record["time"]["command_seconds"] == 0

    def test_a_server_that_generates_slowly_is_the_machinerys_failure(self):
        with ScriptedChatServer(SCRIPT, chunk_delay=0.25) as server:
            record, _box = _run(server, task=self._task(), min_tokens_per_second=1000)
        assert record["finish_state"] == "backstop" and record["trainable"] is False
        # The measured generation speed is in the record: a few tokens a second.
        speed = record["time"]["generation_tokens_per_second"]
        assert speed is not None and speed < 100
        assert record["budgets"]["min_tokens_per_second"] == 1000

    def test_long_sleeps_cannot_make_the_record_untrainable(self):
        """No budget on the commands' time here, so the model can sleep up to the
        backstop.  The server was fast, so that is the model's own timeout."""
        with ScriptedChatServer([_bash("sleep 30"), {"content": "late"}]) as server:
            record, _box = _run(server, task=self._task(), **FAST)
        assert record["finish_state"] == "timeout" and record["finish_cause"] == "model"
        assert record["trainable"] is True
        assert record["timeout"]["cause"].startswith("the server kept its minimum speed")

    def test_a_long_prompt_of_the_models_making_is_not_the_servers_slowness(self):
        """The model fills its context, and the server takes its time over the long
        prompt.  At the minimum prompt speed that is how long such a prompt takes,
        so the time is the model's: it cannot buy an untrainable record with output."""
        script = [_bash("yes aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa | head -c 60000"), {}]
        # The scripted server takes a second for 8,000 tokens of prompt, and the
        # command's output makes a prompt of some 32,000; the minimum the server
        # is held to is 4,000 a second.
        with ScriptedChatServer(script, prompt_tokens_per_second=8_000) as server:
            record, _box = _run(
                server,
                task=self._task(timeout=3),
                max_output_chars=60_000,
                min_tokens_per_second=1e6,
                min_prompt_tokens_per_second=4_000,
            )
            requests = len(server.requests)
        assert requests == 2  # the second, with the long prompt, was under way
        assert record["finish_state"] == "timeout" and record["finish_cause"] == "model"
        assert record["trainable"] is True
        said = record["timeout"]
        assert said["model_seconds"] < said["model_seconds_at_minimum_speed"]

    def test_the_same_prompt_on_a_server_below_its_minimum_is_the_machinerys(self):
        script = [_bash("yes aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa | head -c 60000"), {}]
        with ScriptedChatServer(script, prompt_tokens_per_second=8_000) as server:
            record, _box = _run(
                server,
                task=self._task(timeout=3),
                max_output_chars=60_000,
                min_tokens_per_second=1e6,
                min_prompt_tokens_per_second=1e6,
            )
        assert record["finish_state"] == "backstop" and record["trainable"] is False


class TestWithoutATokenBudget:
    """The time limit is the model's, as before."""

    def test_a_slow_server_uses_up_the_models_time(self):
        with ScriptedChatServer(SCRIPT, delay=3.0) as server:
            record, _box = _run(server, task=Task(prompt="slow", timeout=1))
        assert record["finish_state"] == "timeout" and record["finish_cause"] == "model"
        assert record["trainable"] is True
        assert record["budgets"]["wall_clock"] == "the model's time"
        # One request reached the server.  What the session tried after the limit,
        # on a client that was closed by then, has a record and is no such request.
        assert record["time"]["model_calls"] == 1

    def test_a_long_prompt_does_not_turn_silence_into_a_stalled_server(self):
        """A request whose prompt the server is still working on is silent for a
        reason the model can lengthen.  The silence that counts as a stall grows
        with the prompt, so the model cannot move the limit into it."""
        script = [_bash("yes aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa | head -c 60000"), {}]
        with ScriptedChatServer(script, prompt_tokens_per_second=8_000) as server:
            record, _box = _run(
                server,
                task=Task(prompt="fill", timeout=3),
                max_output_chars=60_000,
                server_stall_seconds=0.5,
                min_prompt_tokens_per_second=4_000,
            )
        assert record["finish_state"] == "timeout" and record["trainable"] is True
        said = record["timeout"]
        assert said["waiting_on"] == "model"
        assert said["server_silence_seconds"] < said["server_silence_allowed"]


class TestSetups:
    def _budgets(self, task: Task, **config: Any) -> Budgets:
        settings: dict[str, Any] = {
            "base_url": "http://x/v1",
            "model": "m",
            "context_window": 200_000,
        }
        settings.update(config)
        return effective_budgets(task, RolloutConfig(**settings))

    def test_a_token_budget_needs_the_servers_minimum_speed(self):
        task = Task(prompt="x", max_generated_tokens=1000)
        with pytest.raises(SetupError, match="min_tokens_per_second"):
            self._budgets(task)

    def test_a_task_needs_a_time_limit_or_the_budgets_to_work_one_out(self):
        with pytest.raises(SetupError, match="has no time limit"):
            self._budgets(Task(prompt="x", timeout=None))
        open_ended = Task(prompt="x", timeout=None, max_generated_tokens=1000)
        with pytest.raises(SetupError, match="max_command_seconds"):
            self._budgets(open_ended, min_tokens_per_second=100)

    def test_the_backstop_is_worked_out_from_the_budgets_and_the_minimum_speed(self):
        task = Task(prompt="x", timeout=None, max_generated_tokens=1000, max_command_seconds=10)
        budgets = self._budgets(task, min_tokens_per_second=100)
        # 10 s of generation, 10 s of commands, for each of the 15 turns and 16
        # sub-agents a prompt as long as the window at 10,000 tokens a second and
        # two seconds, half a minute for the harness and a minute to spare.
        assert budgets.wall_seconds == 10 + 10 + 31 * (20 + 2) + 30 + 60
        assert budgets.backstop is True and budgets.prompt_speed == 10_000
        assert backstop_seconds(max_generated_tokens=1000, min_tokens_per_second=100) == 10 + 2 + 90

    @pytest.mark.parametrize(
        "setting",
        [{"max_generated_tokens": 0}, {"max_command_seconds": -1.0}, {"timeout": 0}],
    )
    def test_a_budget_of_nothing_is_refused(self, setting):
        with pytest.raises(SetupError, match="must be above zero"):
            self._budgets(Task(prompt="x", **setting), min_tokens_per_second=10)

    def test_a_setup_that_cannot_work_runs_nothing(self):
        box = _DirSandbox()
        with ScriptedChatServer(SCRIPT) as server:
            config = RolloutConfig(base_url=server.base_url, model="scripted", **SAMPLED)
            with pytest.raises(SetupError):
                run_episode(
                    Task(prompt="x", max_generated_tokens=10),
                    config,
                    sandbox_factory=lambda _t, _c: box,
                    allow_host_execution=True,
                )
            assert server.requests == []
        assert box.root == "" and box.closed == 0


def _call(start: float, end: float | None, *, tokens: int = 0, grant: int | None = None) -> Any:
    call = CallRecord(index=0, streamed=True, request={})
    call.started_at, call.ended_at = start, end
    call.token_ids = list(range(tokens))
    call.token_grant = grant
    return call


class TestTheMeter:
    def test_time_covered_by_intervals_that_overlap(self):
        assert _covered([]) == 0
        assert _covered([(0, 2), (1, 3), (5, 6)]) == 4
        assert _covered([(0, 10), (2, 3)]) == 10

    def test_every_instant_is_the_servers_the_commands_or_the_harnesss(self):
        """A model call under way makes the instant the server's, whatever else runs."""
        now = [0.0]
        calls = [_call(1.0, 3.0), _call(5.0, 9.0), _call(8.0, None)]
        meter = Meter(Budgets(wall_seconds=100), lambda: calls, clock=lambda: now[0])
        now[0] = 4.0
        with meter.tool_batch():  # 4 to 10, with model calls inside from 5 on
            now[0] = 10.0
        split = meter.split(0.0, 12.0)
        assert split == {"model": 2.0 + 7.0, "commands": 1.0, "harness": 2.0}
        assert sum(split.values()) == 12.0

    def test_requests_side_by_side_cannot_overshoot_the_budget_together(self):
        """Each is granted what nothing has generated or may yet generate."""
        calls: list[Any] = []
        meter = Meter(Budgets(wall_seconds=100, max_generated_tokens=100), lambda: calls)
        first, second, third = _call(1.0, None), _call(1.0, None), _call(1.0, None)
        calls.append(first)
        request: dict[str, Any] = {"max_tokens": 70}
        meter.admit(first, request)
        calls.append(second)
        other: dict[str, Any] = {"max_completion_tokens": 70}
        meter.admit(second, other)
        assert (request["max_tokens"], other["max_completion_tokens"]) == (70, 30)
        assert (first.token_grant_cut, second.token_grant_cut) == (False, True)
        calls.append(third)
        with pytest.raises(TokenBudgetError, match="100 generated tokens is used up"):
            meter.admit(third, {"max_tokens": 70})
        # Refused, and the run is not ended by that: what is granted may come back.
        assert meter.ended is None and meter.left() == 0
        # The first ends having generated less than it was granted: that is free again.
        first.token_ids, first.ended_at = list(range(20)), 2.0
        calls.remove(third)
        assert meter.left() == 50
        unlimited: dict[str, Any] = {}
        calls.append(third)
        meter.admit(third, unlimited)
        assert unlimited == {"max_tokens": 50} and third.token_grant_cut is True

    def test_without_a_token_budget_a_request_is_left_alone(self):
        meter = Meter(Budgets(wall_seconds=100), lambda: [])
        request = {"max_tokens": 70}
        meter.admit(_call(1.0, None), request)
        assert request == {"max_tokens": 70} and meter.left() is None


class _NeverSends:
    """Stands in for an SDK client whose requests fail before anything goes out,
    as those of a client that has been closed do."""

    def __init__(self, error: Exception) -> None:
        self._error = error
        self.chat = SimpleNamespace(completions=SimpleNamespace(create=self._create))

    def _create(self, **_request: Any) -> Any:
        raise self._error


class TestWhatTheServerWasAskedToDo:
    """``time.model_calls`` and ``time.prompt_tokens``, and with them what the
    server is allowed at the backstop, count the requests that went out.  Every
    call has a record, also one that never did."""

    MESSAGES = [{"role": "user", "content": "x" * 5000}]

    def test_a_request_made_on_a_closed_client_is_no_work_of_the_servers(self):
        """The session's next try after the time limit: the client was closed at
        the limit.  It used to count as a call, at its prompt's size in bytes."""
        closed = RuntimeError("Cannot send a request, as the client has been closed.")
        client = RecordingClient(_NeverSends(closed))
        budgets = Budgets(wall_seconds=100, min_tokens_per_second=10.0)
        meter = Meter(budgets, lambda: client.calls)
        with pytest.raises(RuntimeError):
            client.chat.completions.create(model="m", messages=self.MESSAGES, stream=True)
        (call,) = client.calls
        # A record like any other, with the request that would have gone out.
        assert call.error and call.ended_at is not None and call.started_at
        assert call.request["messages"] == 1 and call.prompt_bytes > 5000
        now = time.monotonic()
        work = meter.work(now)
        assert (work["model_calls"], work["prompt_tokens"]) == (0, 0)
        assert meter.allowed_model_seconds(now) == 0

    def test_a_request_the_token_budget_refused_is_none_either(self):
        client = RecordingClient(_NeverSends(AssertionError("it went out")))
        budgets = Budgets(wall_seconds=100, max_generated_tokens=10, min_tokens_per_second=10.0)
        meter = Meter(budgets, lambda: client.calls)
        client.gate = meter
        spent = _call(1.0, 2.0, tokens=10)
        spent.request, spent.chunks, spent.prompt_token_ids = {"model": "m"}, 3, [1, 2, 3]
        client.calls.append(spent)
        with pytest.raises(TokenBudgetError):
            client.chat.completions.create(model="m", messages=self.MESSAGES, max_tokens=50)
        assert len(client.calls) == 2 and client.calls[1].request == {}
        work = meter.work(3.0)
        assert (work["model_calls"], work["prompt_tokens"], work["generated_tokens"]) == (1, 3, 10)

    def test_a_request_that_went_out_counts_however_it_ended(self):
        # Cut by the time limit while the server was still working on its prompt:
        # nothing had come back, and it had been out for seconds.
        cut = _call(1.0, 7.0)
        cut.request, cut.prompt_bytes = {"model": "m"}, 4000
        cut.last_heard_at, cut.error = 1.0, "APIConnectionError: Connection error."
        # Failed at once, after the server had answered.
        answered = _call(7.0, 7.01)
        answered.request, answered.chunks = {"model": "m"}, 1
        answered.last_heard_at, answered.error = 7.005, "APIStatusError: no"
        answered.prompt_token_ids = list(range(30))
        # Still under way: counted at the most its prompt can be.
        under_way = _call(8.0, None)
        under_way.prompt_bytes = 500
        meter = Meter(Budgets(wall_seconds=100), lambda: [cut, answered, under_way])
        work = meter.work(9.0)
        assert (work["model_calls"], work["prompt_tokens"]) == (3, 4000 + 30 + 500)
